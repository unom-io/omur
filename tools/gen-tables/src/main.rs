// Prints crates/omur/src/tables_gen.rs on stdout:
//   cargo run -p omur-gen-tables > crates/omur/src/tables_gen.rs
// Everything is computed in f64 and rounded once to f32.
use std::f64::consts::PI;
use std::fmt::Write;

/// The modified Bessel function of the first kind, order 0, by its power series.
fn bessel_i0(x: f64) -> f64 {
    let q = x * x / 4.0;
    let (mut sum, mut term) = (1.0f64, 1.0f64);
    for k in 1..200 {
        term *= q / (k * k) as f64;
        sum += term;
        if term < sum * 1e-20 {
            break;
        }
    }
    sum
}

/// The first half of the 512-point Kaiser-Bessel-derived window, alpha 5: A/52 Table 7.33
/// at full precision.
fn kbd_window() -> Vec<f64> {
    let (m, alpha) = (256usize, 5.0f64);
    let kernel: Vec<f64> = (0..=m)
        .map(|j| {
            let r = 2.0 * j as f64 / m as f64 - 1.0;
            bessel_i0(PI * alpha * (1.0 - r * r).max(0.0).sqrt())
        })
        .collect();
    let total: f64 = kernel.iter().sum();
    let mut acc = 0.0;
    kernel[..m]
        .iter()
        .map(|v| {
            acc += v;
            (acc / total).sqrt()
        })
        .collect()
}

fn table(out: &mut String, doc: &str, name: &str, values: &[f64]) {
    writeln!(out, "/// {doc}").unwrap();
    writeln!(out, "pub(crate) const {name}: [f32; {}] = [", values.len()).unwrap();
    for v in values {
        writeln!(out, "    {:?},", *v as f32).unwrap();
    }
    writeln!(out, "];").unwrap();
}

/// `exp(-i·phase(k)) · scale` for `k in 0..n`, as a real and an imaginary table.
fn twiddles(
    out: &mut String,
    doc: &str,
    name: &str,
    n: usize,
    scale: f64,
    phase: impl Fn(f64) -> f64,
) {
    let (re, im): (Vec<f64>, Vec<f64>) = (0..n)
        .map(|k| {
            let t = phase(k as f64);
            (t.cos() * scale, -t.sin() * scale)
        })
        .unzip();
    table(
        out,
        &format!("{doc}, real part."),
        &format!("{name}_RE"),
        &re,
    );
    table(
        out,
        &format!("{doc}, imaginary part."),
        &format!("{name}_IM"),
        &im,
    );
}

fn main() {
    let mut out = String::new();
    out.push_str(
        "//! Generated by `tools/gen-tables`; do not edit. Regenerate with\n\
         //! `cargo run -p omur-gen-tables > crates/omur/src/tables_gen.rs`. f64 arithmetic,\n\
         //! rounded once to f32: the encoder evaluates no transcendental (docs/design.md D4).\n\
         #![allow(clippy::approx_constant)]\n\n",
    );
    table(
        &mut out,
        "First half of the transform window (Table 7.33): KBD, alpha 5. `w[511 - n] = w[n]`.",
        "WINDOW",
        &kbd_window(),
    );
    twiddles(
        &mut out,
        "FFT twiddles `exp(-2πik/128)`",
        "FFT",
        64,
        1.0,
        |k| 2.0 * PI * k / 128.0,
    );
    twiddles(
        &mut out,
        "Long DCT-IV pre-twiddle `exp(-iπ(4n+1)/1024)`",
        "PRE_LONG",
        128,
        1.0,
        |n| PI * (4.0 * n + 1.0) / 1024.0,
    );
    twiddles(
        &mut out,
        "Long DCT-IV post-twiddle `exp(-iπk/256)`, carrying the -2/512 output scale",
        "POST_LONG",
        128,
        -1.0 / 256.0,
        |k| PI * k / 256.0,
    );
    twiddles(
        &mut out,
        "Short DCT-IV pre-twiddle `exp(-iπ(4n+1)/512)`",
        "PRE_SHORT",
        64,
        1.0,
        |n| PI * (4.0 * n + 1.0) / 512.0,
    );
    twiddles(
        &mut out,
        "Short DCT-IV post-twiddle `exp(-iπk/128)`, carrying the -2/256 output scale",
        "POST_SHORT",
        64,
        -1.0 / 128.0,
        |k| PI * k / 128.0,
    );
    print!("{out}");
}
