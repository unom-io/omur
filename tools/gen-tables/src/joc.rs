/// `joc_num_bands` by `joc_num_bands_idx` (Table 50); Table 54's columns run the other way.
const BANDS: [usize; 8] = [1, 3, 5, 7, 9, 12, 15, 23];

fn ints(out: &mut String, doc: &str, ty: &str, name: &str, values: &[i64]) {
    writeln!(out, "/// {doc}").unwrap();
    writeln!(out, "#[rustfmt::skip]").unwrap();
    writeln!(out, "pub(crate) const {name}: [{ty}; {}] = [", values.len()).unwrap();
    for row in values.chunks(12) {
        let row: Vec<String> = row.iter().map(i64::to_string).collect();
        writeln!(out, "    {},", row.join(", ")).unwrap();
    }
    writeln!(out, "];").unwrap();
}

/// Every symbol's code word and length, walking the tree from the root, the first bit the
/// most significant. Panics unless each symbol is reached exactly once.
fn codes(tree: &[[i16; 2]]) -> (Vec<i64>, Vec<i64>) {
    let n = tree.len() + 1;
    let (mut code, mut len) = (vec![-1i64; n], vec![0i64; n]);
    let mut stack = vec![(0usize, 0i64, 0i64)];
    while let Some((node, word, depth)) = stack.pop() {
        for (bit, &next) in tree[node].iter().enumerate() {
            let (w, d) = (word << 1 | bit as i64, depth + 1);
            if next < 0 {
                let s = (-next - 1) as usize;
                assert_eq!(code[s], -1, "symbol {s} twice");
                (code[s], len[s]) = (w, d);
            } else {
                stack.push((next as usize, w, d));
            }
        }
    }
    assert!(code.iter().all(|c| *c >= 0) && len.iter().all(|l| *l <= 32));
    (code, len)
}

fn huffman(out: &mut String, doc: &str, name: &str, tree: &[[i16; 2]]) {
    let (code, len) = codes(tree);
    ints(
        out,
        &format!("{doc}: code words."),
        "u32",
        &format!("{name}_CODE"),
        &code,
    );
    ints(
        out,
        &format!("{doc}: lengths."),
        "u8",
        &format!("{name}_LEN"),
        &len,
    );
}

pub(crate) fn generate() -> String {
    let mut out = String::new();
    out.push_str(
        "//! Generated by `tools/gen-tables`; do not edit. Regenerate with\n\
         //! `cargo run -p omur-gen-tables -- joc > crates/omur/src/joc/tables.rs`. The QMF\n\
         //! window and the Huffman trees are adapted from oxideav-ac3 0.0.11 (MIT, Karpelès Lab\n\
         //! Inc.), which transcribed them from the spec's table attachment.\n\
         #![allow(clippy::approx_constant, clippy::excessive_precision)]\n\n",
    );
    table(
        &mut out,
        "QWIN, the 64-band QMF prototype (TS 103 420 clause 7.4).",
        "QWIN",
        &QWIN,
    );
    // Q[k] = Re DCT-IV(x)[k] + i (-1)^k DCT-IV(reversed y)[k]: 64 points through 32.
    twiddles(
        &mut out,
        "QMF DCT-IV pre-twiddle `exp(-iπ(4n+1)/256)`",
        "PRE",
        32,
        1.0,
        |n| PI * (4.0 * n + 1.0) / 256.0,
    );
    twiddles(
        &mut out,
        "QMF DCT-IV post-twiddle `exp(-iπk/64)`",
        "POST",
        32,
        1.0,
        |k| PI * k / 64.0,
    );
    twiddles(
        &mut out,
        "32-point FFT twiddles `exp(-2πik/32)`",
        "FFT",
        16,
        1.0,
        |k| 2.0 * PI * k / 32.0,
    );

    let starts: Vec<i64> = TABLE_54
        .iter()
        .map(|(sb, _)| i64::from(*sb))
        .chain([64])
        .collect();
    ints(
        &mut out,
        "First QMF subband of each band of the 23-band split, then 64 (Table 54).",
        "u8",
        "ATOM_START",
        &starts,
    );
    let mut bands = Vec::new();
    for (idx, n) in BANDS.iter().enumerate() {
        let column = 7 - idx;
        let row: Vec<i64> = TABLE_54.iter().map(|(_, c)| i64::from(c[column])).collect();
        assert_eq!(row.last(), Some(&(*n as i64 - 1)));
        assert!(row.windows(2).all(|w| w[1] == w[0] || w[1] == w[0] + 1));
        bands.extend(row);
    }
    ints(
        &mut out,
        "The parameter band of each 23-split band, 23 per `joc_num_bands_idx` (Tables 50, 54).",
        "u8",
        "ATOM_BAND",
        &bands,
    );
    ints(
        &mut out,
        "`joc_num_bands` by `joc_num_bands_idx` (Table 50).",
        "u8",
        "NUM_BANDS",
        &BANDS.map(|b| b as i64),
    );

    huffman(
        &mut out,
        "Table A.1, dense, 96 steps",
        "COARSE_MTX",
        COARSE_MTX,
    );
    huffman(
        &mut out,
        "Table A.2, dense, 192 steps",
        "FINE_MTX",
        FINE_MTX,
    );
    huffman(
        &mut out,
        "Table A.3, sparse, 96 steps",
        "COARSE_VEC",
        COARSE_VEC,
    );
    huffman(
        &mut out,
        "Table A.4, sparse, 192 steps",
        "FINE_VEC",
        FINE_VEC,
    );
    out
}
