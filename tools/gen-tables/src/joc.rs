//! The object-audio tables (ETSI TS 103 420): `cargo run -p omur-gen-tables -- joc >
//! crates/omur/src/joc/tables.rs`. The QMF window and the Huffman trees are transcribed in
//! `joc_data.rs`; the twiddles and the encoder's code words are derived from them here.

